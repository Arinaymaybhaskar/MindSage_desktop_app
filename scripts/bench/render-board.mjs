/**
 * Renders the optimisation status board from measurements rather than memory.
 *
 * Reads docs/benchmarks/issues.json (hand-written: what each issue is, what
 * would count as fixed, and where its number lives) and every stored run in
 * docs/benchmarks/results/, then writes the status-board table back into
 * OPTIMIZATION_LOG.md, between markers. The live equivalent of this board —
 * multi-machine, with trends — is mindsage-web's /benchmarks page, published
 * to via `npm run bench -- --publish`.
 *
 * "Before" is always the `baseline` run. "After" is the most recent run that
 * actually measured that metric, which is why a partial re-run still fills in
 * the rows it covers and leaves the rest alone.
 *
 * Usage: npm run bench:board
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { resolve as resolveMetric, format, meetsTarget, describeChange } from "./lib/metrics.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const benchDir = path.join(repoRoot, "docs", "benchmarks");
const resultsDir = path.join(benchDir, "results");

const BASELINE_LABEL = "baseline";
const START = "<!-- BOARD:START - generated by npm run bench:board, do not edit -->";
const END = "<!-- BOARD:END -->";

const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));

/** Every stored run, oldest first, so "most recent that measured X" is a scan. */
function loadRuns() {
  if (!fs.existsSync(resultsDir)) return [];
  return fs
    .readdirSync(resultsDir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => ({ file: f, ...readJson(path.join(resultsDir, f)) }))
    .filter((r) => r.label && r.timestamp)
    .sort((a, b) => new Date(a.timestamp) - new Date(b.timestamp));
}

/**
 * The newest run other than the baseline that carries this metric.
 *
 * Falling back to "any run that measured it" rather than "the newest run"
 * matters: a db-only re-run must not blank the AI rows, and an AI-only run must
 * not blank the db rows.
 */
function latestMeasuring(runs, selector, baselineLabels, baselineCommit) {
  for (let i = runs.length - 1; i >= 0; i -= 1) {
    const run = runs[i];
    // A run of the same code is a re-measurement, not an improvement. Showing
    // it as an "after" would claim a fix that never happened.
    if (baselineLabels.includes(run.label)) continue;
    if (baselineCommit && run.commit === baselineCommit && !run.dirty) continue;
    const value = resolveMetric(run, selector);
    if (value != null) return { run, value };
  }
  return null;
}

const SEVERITY_MARK = {
  high: "🔴",
  moderate: "🟠",
  low: "🟡",
  closed: "✅",
};

function buildRows(issues, runs, baseline, baselineLabels) {
  return issues.map((issue) => {
    const sel = issue.metric;
    const before = baseline ? resolveMetric(baseline, sel) : null;
    const after = latestMeasuring(runs, sel, baselineLabels, baseline?.commit);
    // A target of zero means "remove this step entirely", which reads as
    // nonsense formatted as "< 0.00ms".
    const target =
      sel.target === 0
        ? "eliminate"
        : typeof sel.target === "number"
          ? `${sel.higherIsBetter ? ">" : "<"} ${format({ value: sel.target }, sel)}`
          : "—";
    const hit = after ? meetsTarget(after.value, sel) : null;
    const change = after ? describeChange(before, after.value, sel) : null;

    return {
      ...issue,
      beforeText: format(before, sel),
      afterText: after ? format(after.value, sel) : "—",
      afterLabel: after?.run.label ?? null,
      targetText: target,
      changeText: change ?? "—",
      hitTarget: hit,
      moved: change != null && change !== "unchanged" && change !== "—",
      worse: Boolean(change && (change.includes("slower") || change.includes("worse"))),
      progress: progressToTarget(before, after?.value, sel),
      missing: before == null,
    };
  });
}

/**
 * How far the metric has travelled from its baseline toward its target, 0-100.
 *
 * Rendered as a bar, so it has to be an actual measurement rather than a
 * decorative fraction - a progress bar that does not track progress is worse
 * than no bar, because it looks like information.
 */
function progressToTarget(before, after, sel) {
  if (!before || !after || before.text || after.text) return null;
  if (typeof sel.target !== "number") return null;
  const span = sel.target - before.value;
  if (span === 0) return null;
  const travelled = (after.value - before.value) / span;
  return Math.max(0, Math.min(100, travelled * 100));
}

function statusCell(r) {
  const mark = SEVERITY_MARK[r.severity] ?? "🟡";
  if (r.severity === "closed") return "✅ closed, no action";
  if (r.hitTarget === true) return "✅ fixed and verified";
  if (r.worse) return `${mark} regressed`;
  if (r.moved) return `${mark} improved, target not met`;
  if (r.afterLabel) return `${mark} re-measured, no change`;
  return `${mark} open`;
}

// --------------------------------------------------------------- markdown ---

function renderMarkdown(rows, baseline, runs) {
  const lines = [
    START,
    "",
    `_Generated from \`results/\` by \`npm run bench:board\` — every figure below is`,
    `read out of a stored run, so none of them can go stale. Before = \`${BASELINE_LABEL}\``,
    `(${baseline?.timestamp?.slice(0, 10) ?? "—"}${baseline?.commit ? `, \`${baseline.commit.slice(0, 8)}\`` : ""}).`,
    `After = the most recent run that measured each metric. ${runs.length} runs on record._`,
    "",
    "| ID | Issue | Key metric | Before | Target | After | Change | Status |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const r of rows) {
    lines.push(
      [
        "",
        `**${r.id}**`,
        r.title,
        r.metricLabel,
        r.missing ? "_not in baseline_" : `**${r.beforeText}**`,
        r.targetText,
        r.afterLabel ? `**${r.afterText}** _(${r.afterLabel})_` : "—",
        r.changeText,
        statusCell(r),
        "",
      ].join(" | ").trim()
    );
  }

  lines.push(
    "",
    "Legend: 🔴 high · 🟠 moderate · 🟡 low · ✅ done and verified",
    "",
    END
  );
  return lines.join("\n");
}

// ------------------------------------------------------------------- main ---

const manifest = readJson(path.join(benchDir, "issues.json"));
const issues = manifest.issues;
const baselineLabels = manifest.baselineLabels ?? [BASELINE_LABEL];
const runs = loadRuns();
const baseline = runs.find((r) => r.label === BASELINE_LABEL);

if (!baseline) {
  console.error(`No run labelled "${BASELINE_LABEL}" in ${resultsDir}.`);
  process.exit(1);
}

const rows = buildRows(issues, runs, baseline, baselineLabels);

const logPath = path.join(benchDir, "OPTIMIZATION_LOG.md");
const log = fs.readFileSync(logPath, "utf8");
const board = renderMarkdown(rows, baseline, runs);

if (!log.includes(START) || !log.includes(END)) {
  console.error(`Markers not found in OPTIMIZATION_LOG.md. Add:\n${START}\n${END}`);
  process.exit(1);
}
const updated = log.replace(
  new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`),
  board
);
fs.writeFileSync(logPath, updated);

const stale = rows.filter((r) => r.missing);
console.log(`Board: ${rows.length} issues, ${runs.length} runs.`);
if (stale.length) {
  console.log(`  ${stale.length} metric(s) absent from the baseline: ${stale.map((r) => r.id).join(", ")}`);
}
console.log(`Wrote ${path.relative(repoRoot, logPath)}`);
